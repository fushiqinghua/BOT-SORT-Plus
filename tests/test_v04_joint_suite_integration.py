"""One end-to-end J0/J1/J2/J3/E3/package software fixture.

Requires the optional pinned runtime and J1_TRACKEVAL_ROOT. Six synthetic frames
exercise orchestration, not benchmark accuracy. All three camera fixture caches
select the actual native transform, so the G=native alias is exact in this test.
"""
from copy import deepcopy
import csv
import gzip
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import unittest
import zipfile

REPO = Path(__file__).resolve().parents[1]
TRACKEVAL = os.environ.get("J1_TRACKEVAL_ROOT", "")
READY = bool(TRACKEVAL) and all(importlib.util.find_spec(name) is not None for name in ("boxmot", "torch", "cv2"))


@unittest.skipUnless(READY, "requires optional pinned runtime and J1_TRACKEVAL_ROOT")
class JointSuiteIntegrationTests(unittest.TestCase):
    def test_real_suite_pipeline_on_synthetic_six_frames(self):
        spec = importlib.util.spec_from_file_location("joint_worker_fixture_for_suite", REPO / "tests/test_v04_joint_worker.py")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        helper = module.JointWorkerCLITests("test_preflight_is_persisted_and_prediction_rejects_gt_settings")
        helper.setUp()
        self.addCleanup(helper.doCleanups)
        root, seq, fixture = helper.root, helper.sequence, helper.fixture
        settings = deepcopy(helper.settings)
        refs = root / "reference_runs"

        # Genuine native-disabled reference generated by the original runner.
        from botsort_plus.config import PlusConfig
        native_config = root / "native_config.json"
        helper.write(native_config, PlusConfig(name="native").to_dict())
        command = [sys.executable, str(REPO / "tools/run_botsort_plus.py"),
                   "--baseline-root", str(fixture.baseline), "--features-dir", str(fixture.features),
                   "--images-root", str(fixture.images), "--config", str(native_config),
                   "--output-dir", str(refs), "--sequences", seq, "--trace"]
        native = subprocess.run(command, cwd=REPO, env=helper.environment, text=True,
                                capture_output=True, timeout=75)
        helper.success(native)
        status, b_root = helper.invoke("B_early_moderate", "reference_B_live")
        helper.success(status)
        b_protocol = helper.manifest(b_root, "B_early_moderate")

        # Synthetic candidate-set sources: identical *actual* SOF matrices,
        # never a fabricated accuracy improvement or LightGlue inference.
        with gzip.open(b_root / "warps/B_early_moderate" / (seq + ".jsonl.gz"), "rt") as stream:
            camera_rows = [json.loads(line) for line in stream]
        self.assertTrue(all(row["choice"] == "sof" for row in camera_rows))
        base_contract = json.loads((REPO / "experiments/vttiny_gmc/reference.json").read_text())["gmc_factorial"]
        cache = root / "SYNTHETIC_CAMERA_SOURCES_ONLY"
        settings.update(gmc_mode="cached", warp_sources={})
        for camera, skip, lg in (("native", False, False), ("skip_only", True, False), ("adaptive_gmc", True, True)):
            protocol = deepcopy(b_protocol)
            protocol["gmc_factorial"] = deepcopy(base_contract)
            protocol["gmc_factorial"].update(skip=skip, lightglue=lg)
            if not lg:
                protocol["gmc_factorial"]["model"] = None
            protocol["synthetic_software_test_only"] = True
            protocol["fixture_note"] = "All selections equal measured SOF; adaptive candidate-set plumbing fixture only"
            helper.write(cache / "protocols" / (camera + ".json"), protocol)
            dest = cache / "warps" / camera / (seq + ".jsonl.gz")
            dest.parent.mkdir(parents=True)
            with gzip.open(dest, "wt", encoding="utf-8") as stream:
                for row in camera_rows:
                    stream.write(json.dumps(row) + "\n")
            settings["warp_sources"][camera] = {"run_dir": str(cache), "method": camera}

        # With selected matrices equal native and no LG-selected frames, the
        # declared synthetic G arm has exactly native behavior and no guard.
        native_protocol = json.loads((refs / "protocols/native.json").read_text())
        g_protocol = deepcopy(native_protocol)
        g_protocol["name"] = "dual_low"
        g_protocol["config"]["name"] = "dual_low"
        g_protocol["synthetic_equivalence_fixture"] = {
            "source": "native", "reason": "every selected matrix equals native; no dual_low activation"}
        helper.write(refs / "protocols/dual_low.json", g_protocol)
        shutil.copytree(refs / "trackers/native", refs / "trackers/dual_low")
        shutil.copytree(refs / "events/native", refs / "events/dual_low")
        bg_status, bg_root = helper.invoke("B_early_moderate_dual_low", "reference_BG_cached", settings=settings)
        helper.success(bg_status)
        bg_protocol = helper.manifest(bg_root, "B_early_moderate_dual_low")
        self.assertEqual(b_protocol["output_prediction_hashes"], bg_protocol["output_prediction_hashes"])

        gt = root / "SYNTHETIC_GT_ONLY" / seq / "gt/gt.txt"
        gt.parent.mkdir(parents=True)
        gt.write_text("".join(f"{frame},0,50,50,4,4,1,1,1\n" for frame in range(1,7)), encoding="utf-8")
        output = root / "joint_batch_synthetic"
        settings.update(gt_root=str(gt.parents[2]), trackeval_root=str(Path(TRACKEVAL).resolve()),
                        output_root=str(output), sequences=[seq], original_video_groups={seq:"synthetic_source_video"},
                        references={"native":{"run_dir":str(refs),"tracker":"native"},
                                    "B":{"run_dir":str(b_root),"tracker":"B_early_moderate"},
                                    "G":{"run_dir":str(refs),"tracker":"dual_low"},
                                    "BG":{"run_dir":str(bg_root),"tracker":"B_early_moderate_dual_low"}})
        settings_path = root / "suite_settings.json"
        helper.write(settings_path, settings)
        result = subprocess.run([sys.executable, str(REPO / "tools/run_v04_joint_batch.py"),
                                 "run", "--settings", str(settings_path)],
                                cwd=REPO, env=helper.environment, text=True, capture_output=True, timeout=240)
        if result.returncode:
            # Keep a bounded diagnostic outside the temporary fixture tree.
            log = REPO.parent / "joint_suite_integration_failure.log"
            log.write_text(result.stdout + "\n" + result.stderr, encoding="utf-8")
        self.assertEqual(result.returncode, 0, (result.stdout + "\n" + result.stderr)[-18000:])
        state = json.loads((output / "batch_status.json").read_text())
        self.assertEqual(state["status"], "COMPLETE_EXECUTABLE_STAGES")
        self.assertEqual(set(state["stages"]), {"J0","J1","smoke","J2","J2_evaluation", "J3_BG",
                                               "J3_F_summary","J3_BG_summary","E3_prepare"})
        self.assertEqual(state["J4"], "AWAITING_DIAGNOSTIC_DECISION")
        self.assertEqual(state["E3"], "PENDING_HUMAN_REVIEW")
        self.assertEqual(json.loads((output / "smoke/verification.json").read_text())["status"], "PASS")
        for name in ("j1", "j3_f_analysis", "j3_bg_analysis"):
            self.assertEqual(json.loads((output / name / "manifest.json").read_text())["status"], "COMPLETE")
        metrics = json.loads((output / "j2_evaluation/metrics/summary.json").read_text())
        combined = {row["tracker"]:row for row in metrics["results"] if row["sequence"] == "COMBINED_SEQ"}
        self.assertEqual(set(combined), {"native","dual_low","B_early_moderate","B_early_moderate_dual_low",
                                         "B_skip_only","B_adaptive_no_dual_low"})
        self.assertEqual(combined["native"]["FN"], 5)
        self.assertEqual(combined["B_early_moderate"]["FN"], 3)
        self.assertEqual(combined["B_skip_only"]["FN"], 3)
        self.assertEqual(combined["B_adaptive_no_dual_low"]["FN"], 3)
        archive = Path(state["evidence"]["path"])
        self.assertTrue(archive.is_file())
        with zipfile.ZipFile(archive) as bundle:
            names = bundle.namelist()
            self.assertIn("batch_status.json", names)
            self.assertIn("j2_evaluation/metrics/summary.json", names)
            self.assertFalse(any(Path(name).name == "gt.txt" for name in names))
            self.assertFalse(any("probes" in Path(name).parts or "warps" in Path(name).parts for name in names))
        reviews = list((output / "e3_review").rglob("*manual_review*.csv"))
        self.assertTrue(reviews)
        with reviews[0].open(encoding="utf-8-sig", newline="") as stream:
            labels = list(csv.DictReader(stream))
        self.assertEqual(len(labels), 22)
        self.assertTrue(all(row["human_label"] == "pending" for row in labels))


if __name__ == "__main__":
    unittest.main()
